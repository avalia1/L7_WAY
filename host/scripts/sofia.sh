}

sofia_contains() {
    local path=$1
    if [[ "$path" == ${HOME}/.l7* ]] || [[ "$path" == ${HOME}/Backup/L7_WAY* ]]; then
        echo "within"; return 0
    fi
    echo "outside"; return 1
}

# ─── SIGNAL (THE RATTLE) ───
sofia_signal() {
    local severity=${1:-"NOTICE"} message=${2:-""}
    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    sofia_log "SIGNAL [${severity}]: ${message}"
    python3 -c "
import json
with open('${HOME}/.l7/state/sofia-signal.json', 'w') as f:
    json.dump({'time':'${ts}','severity':'${severity}','message':'''${message}''','source':'sofia'}, f, indent=2)
" 2>/dev/null
    chmod 600 "${HOME}/.l7/state/sofia-signal.json" 2>/dev/null
    if [[ -t 1 ]]; then
        case $severity in
            BREACH) echo "  [!!!] ${message}" ;; ALARM) echo "  [!!]  ${message}" ;;
            ALERT)  echo "  [!]   ${message}" ;; *)     echo "  [~]   ${message}" ;;
        esac
    fi
}

