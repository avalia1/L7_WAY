# Stage 5: BREATH (Sofia) — the space between. The home changed. Begin again.
sofia_breath() {
    local next=${1:-""}

    if [[ ! -f "$SOFIA_CURRENT" ]]; then
        sofia_log "BREATH on empty manifold"
        return 1
    fi

    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    local cycle_id=$(python3 -c "import json; print(json.load(open('${SOFIA_CURRENT}'))['cycle_id'])" 2>/dev/null)
    local domain=$(python3 -c "import json; print(json.load(open('${SOFIA_CURRENT}'))['domain'])" 2>/dev/null)

    python3 -c "
import json
with open('${SOFIA_CURRENT}') as f: c = json.load(f)
c['stage'] = 'BREATH'
c['junction'] = 'sofia'
c['completed'] = '${ts}'
c['breath'] = {'time': '${ts}', 'next': '''${next}'''}
with open('${SOFIA_CURRENT}', 'w') as f: json.dump(c, f, indent=2)
" 2>/dev/null

    local archive="${SOFIA_HISTORY}/${domain}-${cycle_id}.json"
    cp "$SOFIA_CURRENT" "$archive"
    chmod 600 "$archive"

    sofia_log "BREATH [${domain}]: cycle complete. Next: ${next}"
    rm -f "$SOFIA_CURRENT"
    echo "BREATH"
}

# ─── FULL CYCLE ───
sofia_cycle() {
    local domain=$1 action=$2 question=$3 synthesis=$4 reaction=$5 result=$6 next=$7
    sofia_action "$domain" "$action"
    sofia_question "$question"
    sofia_synthesis "$synthesis"
    sofia_reaction "$reaction" "$result"
    sofia_breath "$next"
}

