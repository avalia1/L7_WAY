# Stage 4: RE-ACTION (Rubedo) — respond, not repeat, spiral
sofia_reaction() {
    local reaction=$1
    local result=$2

    if [[ ! -f "$SOFIA_CURRENT" ]]; then
        sofia_log "RE-ACTION without prior stages"
        return 1
    fi

    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

    python3 -c "
import json
with open('${SOFIA_CURRENT}') as f: c = json.load(f)
c['stage'] = 'RE-ACTION'
