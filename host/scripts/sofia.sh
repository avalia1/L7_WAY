# Stage 1: ACTION (Nigredo) — do, dissolve by doing
sofia_action() {
    local domain=$1
    local action=$2
    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

    cat > "$SOFIA_CURRENT" << ACTEND
{
  "cycle_id": "$(date +%s)",
  "domain": "${domain}",
  "stage": "ACTION",
  "junction": "nigredo",
  "started": "${ts}",
  "action": {
    "time": "${ts}",
    "what": "${action}"
  }
}
ACTEND
    chmod 600 "$SOFIA_CURRENT"
    sofia_log "ACTION [${domain}]: ${action}"
    echo "ACTION"
}

# Stage 2: QUESTION (Albedo) — the doing reveals what must be asked
sofia_question() {
    local question=$1

    if [[ ! -f "$SOFIA_CURRENT" ]]; then
        sofia_log "QUESTION without ACTION — you cannot ask without first doing"
        return 1
    fi

    local ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

    python3 -c "
import json
with open('${SOFIA_CURRENT}') as f: c = json.load(f)
c['stage'] = 'QUESTION'
c['junction'] = 'albedo'
c['question'] = {'time': '${ts}', 'what': '''${question}'''}
with open('${SOFIA_CURRENT}', 'w') as f: json.dump(c, f, indent=2)
" 2>/dev/null

    sofia_log "QUESTION [$(python3 -c "import json; print(json.load(open('${SOFIA_CURRENT}'))['domain'])" 2>/dev/null)]: ${question}"
    echo "QUESTION"
}

# Stage 3: SYNTHESIS (Citrinitas) — understanding crystallizes
sofia_synthesis() {
